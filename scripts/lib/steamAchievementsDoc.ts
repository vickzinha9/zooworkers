import { ACHIEVEMENTS } from '../../src/content/achievements';
import { steamAchievementId } from '../../src/platform/achievements';
import en from '../../src/i18n/locales/en.json';
import ptBR from '../../src/i18n/locales/pt-BR.json';
import { format, resolveConfig } from 'prettier';

// The table a person copies into the Steamworks partner site (Stats & Achievements):
// one row per achievement in the game, its API name, whether it is hidden, and its
// name and description in both complete languages. Generated from the game's own
// data, so it cannot drift: tests/steamAchievementsDoc.test.ts compares the
// committed docs/STEAM_ACHIEVEMENTS.md with this output.

type Tree = Record<string, unknown>;

function text(locale: Tree, key: string): string {
  const value = key.split('.').reduce<unknown>((node, part) => (node as Tree)?.[part], locale);
  if (typeof value !== 'string') throw new Error(`missing string ${key}`);
  return value;
}

/** Table cells hold plain text: pipes escaped, no line breaks. */
function cell(value: string): string {
  return value.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
}

function renderRaw(): string {
  const rows = ACHIEVEMENTS.map((achievement) =>
    [
      `\`${steamAchievementId(achievement.id)}\``,
      achievement.hidden ? 'yes' : 'no',
      cell(text(en as Tree, achievement.nameKey)),
      cell(text(en as Tree, achievement.descriptionKey)),
      cell(text(ptBR as Tree, achievement.nameKey)),
      cell(text(ptBR as Tree, achievement.descriptionKey)),
    ].join(' | '),
  );
  return [
    '# Steam achievements',
    '',
    'Generated by `npx tsx scripts/steam-achievements.ts` from the game data; do not edit by hand.',
    `The game has ${ACHIEVEMENTS.length} achievements. Create each on the Steamworks partner site`,
    '(Stats & Achievements) with this API name, set "Hidden" as listed, and enter the English',
    'and Portuguese (Brazil) name and description. Each also needs two 64×64 icons (achieved',
    'and unachieved), which are not made yet: see `docs/STEAM_ASSET_CHECKLIST.md`.',
    '',
    'The game unlocks achievements in the save whether or not Steam is running;',
    '`src/platform/achievements.ts` mirrors each unlock to Steam by these names once a',
    'Steamworks binding is wired (see `docs/STEAM.md`).',
    '',
    '| API name | Hidden | Name (EN) | Description (EN) | Nome (pt-BR) | Descrição (pt-BR) |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows.map((row) => `| ${row} |`),
    '',
  ].join('\n');
}

/** The document as committed: the table, formatted the way Prettier keeps the repo. */
export async function renderSteamAchievementsDoc(): Promise<string> {
  const target = new URL('../../docs/STEAM_ACHIEVEMENTS.md', import.meta.url);
  const options = (await resolveConfig(target)) ?? {};
  return format(renderRaw(), { ...options, filepath: target.pathname, parser: 'markdown' });
}
